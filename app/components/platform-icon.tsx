import type { ReactElement } from "react";
import iconsJson from "~/lib/icons.json";
import type { IconifyJSON } from "@iconify/types";

// Type declaration for the iconify-icon web component used in JSX.
declare module "react" {
    // eslint-disable-next-line @typescript-eslint/no-namespace
    namespace JSX {
        interface IntrinsicElements {
            "iconify-icon": React.DetailedHTMLProps<React.HTMLAttributes<HTMLElement>, HTMLElement> & {
                icon: string;
                width?: string | number;
                height?: string | number;
                inline?: boolean;
            };
        }
    }
}

// Minimal icon collections generated by `pnpm icons` (scripts/build-icons.mjs).
// Contains ONLY the icons used on the site (~1 KB) — no network requests,
// no 8 MB icon set bundle.
const collections = Object.values(iconsJson) as IconifyJSON[];

let registered = false;
export async function ensureIconsRegistered() {
    if (registered || typeof window === "undefined") return;
    const { addCollection } = await import("iconify-icon");
    for (const data of collections) {
        addCollection(data);
    }
    registered = true;
}

export function PlatformIcon({ name }: { name: string }): ReactElement {
    void ensureIconsRegistered();
    return <iconify-icon icon={name} inline aria-hidden="true" />;
}
 